// Builds the word files the game loads. Run from the repo root: node tools/build-words.mjs
//
//   words/en.txt   every English word the game accepts (an-array-of-english-words, a-z only)
//   words/ur.txt   Roman Urdu words, from tools/urdu-source.txt with verb forms added
//   js/prompts.js  English letter prompts by difficulty, plus the blocked-word list
//   words/bot.txt  answers for the computer players: per prompt, common words that contain it (see below)
//
// Prompt difficulty is how many *common* English words (Google's 20k list, 5+ letters)
// contain the letters, so every prompt has answers normal people know, at any minimum length.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const SOURCES = {
  en: 'https://cdn.jsdelivr.net/npm/an-array-of-english-words@2.0.0/index.json',
  common: 'https://raw.githubusercontent.com/first20hours/google-10000-english/master/20k.txt',
  bad: 'https://cdn.jsdelivr.net/gh/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words@master/en',
};
// Prompt bands: [min, max) common words containing the letters, per prompt length
const BANDS = {
  easy: { 2: [300, Infinity], 3: [70, Infinity] },
  normal: { 2: [80, 300], 3: [22, 70] },
  hard: { 2: [15, 80], 3: [7, 22] },
};
const VERB_ENDINGS = ['na', 'ne', 'ni', 'ta', 'te', 'ti', 'o', 'ein', 'ega', 'egi', 'enge', 'unga', 'ungi', 'kar', 'ke'];

async function get(name) {
  const file = `tools/.cache/${name}`;
  if (!existsSync(file)) {
    mkdirSync('tools/.cache', { recursive: true });
    const res = await fetch(SOURCES[name]);
    if (!res.ok) throw new Error(`Download failed: ${SOURCES[name]}`);
    writeFileSync(file, await res.text());
  }
  return readFileSync(file, 'utf8');
}

const isWord = (w) => /^[a-z]{2,20}$/.test(w);

const blocked = [...new Set((await get('bad')).split('\n').map((s) => s.trim().toLowerCase()).filter(isWord))].sort();
const blockedSet = new Set(blocked);
const en = [...new Set(JSON.parse(await get('en')).filter(isWord))].sort();
const enSet = new Set(en);

// Roman Urdu
const ur = new Set();
for (const raw of readFileSync('tools/urdu-source.txt', 'utf8').split('\n')) {
  const line = raw.trim().toLowerCase();
  if (!line || line.startsWith('#')) continue;
  if (line.startsWith('@verb')) {
    for (const root of line.slice(5).trim().split(/\s+/)) {
      if (!isWord(root)) continue;
      ur.add(root);
      for (const end of VERB_ENDINGS) {
        // kha + o = khao, kar + o = karo; a root ending in a vowel doesn't double it
        const word = root.endsWith(end[0]) && /[aeiou]/.test(end[0]) ? root + end.slice(1) : root + end;
        if (isWord(word)) ur.add(word);
      }
    }
    continue;
  }
  for (const w of line.split(/\s+/)) if (isWord(w)) ur.add(w);
}
const urList = [...ur].filter((w) => !blockedSet.has(w)).sort();

// Prompts
const common = [...new Set((await get('common')).split('\n').map((s) => s.trim()))]
  .filter((w) => /^[a-z]{5,20}$/.test(w) && enSet.has(w) && !blockedSet.has(w));
const counts = new Map();
for (const w of common) {
  const seen = new Set();
  for (let n = 2; n <= 3; n++) for (let i = 0; i + n <= w.length; i++) seen.add(w.slice(i, i + n));
  for (const k of seen) counts.set(k, (counts.get(k) || 0) + 1);
}
const prompts = {};
for (const [band, lens] of Object.entries(BANDS)) {
  prompts[band] = {};
  for (const [len, [lo, hi]] of Object.entries(lens)) {
    prompts[band][len] = [...counts].filter(([k, c]) => k.length === Number(len) && c >= lo && c < hi && !blockedSet.has(k))
      .map(([k]) => k).sort().join(' ');
  }
}

// Computer players (rooms): finding a word that contains the letters by scanning 274k words costs far more than the
// server's 10 ms per event, so every prompt gets a short list of everyday words that contain it, made here.
// One line per prompt: "ab word word ...". The list is in the order of Google's 20k (most common first); a bot
// picks among the first few, so it plays everyday words and is beatable by anyone who knows longer ones.
const BOT_WORDS = 24;
const allPrompts = [...new Set(Object.values(prompts).flatMap((lens) => Object.values(lens).flatMap((s) => s.split(' ').filter(Boolean))))].sort();
const botLines = allPrompts.map((p) => `${p} ${common.filter((w) => w.includes(p)).slice(0, BOT_WORDS).join(' ')}`);
mkdirSync('words', { recursive: true });
writeFileSync('words/en.txt', en.join('\n') + '\n');
writeFileSync('words/ur.txt', urList.join('\n') + '\n');
writeFileSync('words/bot.txt', botLines.join('\n') + '\n');
writeFileSync('js/prompts.js', `// Generated by tools/build-words.mjs. Do not edit by hand.
// English letter prompts by difficulty and length, space separated.
export const PROMPTS = ${JSON.stringify(prompts, null, 2)};

// Words never accepted as answers (LDNOOBW list, single words).
export const BLOCKED = ${JSON.stringify(blocked.join(' '))};
`);

console.log(`en ${en.length} words, ur ${urList.length} words, ${common.length} common words for prompts`);
for (const [band, lens] of Object.entries(prompts)) {
  console.log(band, Object.entries(lens).map(([len, s]) => `${len}: ${s.split(' ').length}`).join(', '));
}
