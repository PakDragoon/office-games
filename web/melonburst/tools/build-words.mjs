// Builds the word files the game loads. Run from the repo root: node tools/build-words.mjs
//
//   words/common.txt  everyday words the computer can pick (SCOWL sizes 10 and 20)
//   words/more.txt    more common words it can also pick (SCOWL size 35)
//   words/valid.txt   every word a player may pick for someone else (an-array-of-english-words + the above)
//   js/blocked.js     words never accepted or picked (the LDNOOBW list)
//
// SCOWL (wordlist-english) is split by how common a word is and keeps proper nouns in separate
// lists, so the computer only picks real, reasonably well-known words. Plurals whose singular is
// also on the list are dropped from the computer's lists (players can still pick them).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const SCOWL = (n) => `https://cdn.jsdelivr.net/npm/wordlist-english@1.2.1/english-words-${n}.json`;
const SOURCES = {
  s10: SCOWL(10),
  s20: SCOWL(20),
  s35: SCOWL(35),
  en: 'https://cdn.jsdelivr.net/npm/an-array-of-english-words@2.0.0/index.json',
  bad: 'https://cdn.jsdelivr.net/gh/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words@master/en',
};
export const MIN_LEN = 4;
export const MAX_LEN = 12;

async function get(name) {
  const file = `tools/.cache/${name}`;
  if (!existsSync(file)) {
    mkdirSync('tools/.cache', { recursive: true });
    const res = await fetch(SOURCES[name]);
    if (!res.ok) throw new Error(`Download failed: ${SOURCES[name]}`);
    writeFileSync(file, await res.text());
  }
  return readFileSync(file, 'utf8');
}

const isWord = (w) => typeof w === 'string' && new RegExp(`^[a-z]{${MIN_LEN},${MAX_LEN}}$`).test(w);

const blocked = [...new Set((await get('bad')).split('\n').map((s) => s.trim().toLowerCase()).filter((w) => /^[a-z]{2,20}$/.test(w)))].sort();
const blockedSet = new Set(blocked);
// Words containing a blocked word of 4+ letters are out too (but "class" isn't out for "ass")
const blockedLong = blocked.filter((b) => b.length >= 4);
const clean = (w) => !blockedSet.has(w) && !blockedLong.some((b) => w.includes(b));

const load = async (name) => JSON.parse(await get(name)).map((w) => String(w).toLowerCase()).filter(isWord).filter(clean);
const s10 = await load('s10');
const s20 = await load('s20');
const s35 = await load('s35');

// Drop plurals and -s verb forms when the base word is on the list too
function bases(list) {
  const all = new Set(list);
  return list.filter((w) => {
    if (w.endsWith('ies') && all.has(w.slice(0, -3) + 'y')) return false;
    if (w.endsWith('es') && all.has(w.slice(0, -2))) return false;
    if (w.endsWith('s') && !w.endsWith('ss') && all.has(w.slice(0, -1))) return false;
    return true;
  });
}
const everyday = new Set([...s10, ...s20]);
const common = [...new Set(bases([...everyday]))].sort();
const commonSet = new Set(common);
const more = bases([...new Set([...s10, ...s20, ...s35])]).filter((w) => !everyday.has(w) && !commonSet.has(w)).sort();

const en = (await load('en'));
const valid = [...new Set([...en, ...common, ...more, ...s10, ...s20, ...s35])].sort();

mkdirSync('words', { recursive: true });
writeFileSync('words/common.txt', common.join('\n') + '\n');
writeFileSync('words/more.txt', more.join('\n') + '\n');
writeFileSync('words/valid.txt', valid.join('\n') + '\n');
writeFileSync('js/blocked.js', `// Generated by tools/build-words.mjs from the LDNOOBW list. Never accepted or picked.\nexport const BLOCKED = ${JSON.stringify(blocked)};\n`);

const byLen = (list) => Object.entries(list.reduce((m, w) => { m[w.length] = (m[w.length] || 0) + 1; return m; }, {})).map(([k, v]) => `${k}:${v}`).join(' ');
console.log(`common ${common.length} (${byLen(common)})`);
console.log(`more   ${more.length} (${byLen(more)})`);
console.log(`valid  ${valid.length}`);
console.log(`blocked ${blocked.length}`);
